const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
(async () => {
  const browser = await chromium.launch({headless: true});
  const page = await browser.newPage({viewport: {width:1280,height:1000}});
  const errors=[];page.on('pageerror', e=>errors.push(e.message));
  await page.goto('https://185.216.22.24.sslip.io', {waitUntil:'networkidle'});
  await page.screenshot({path:'data/ui-desktop.png',fullPage:true});
  await page.locator('#key').fill('incorrect-key');
  await page.locator('#file').setInputFiles('open/videos/Х-8.mov');
  await page.getByRole('button',{name:'Начать проверку'}).click();
  await page.getByText('Неверный ключ доступа.',{exact:false}).waitFor();
  await page.screenshot({path:'data/ui-error.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'data/ui-mobile.png',fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  console.log(JSON.stringify({errors,mobileHorizontalOverflow:overflow,title:await page.title()}));
  await browser.close();
})();
